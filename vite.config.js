import { defineConfig } from 'vite';
import vue from '@vitejs/plugin-vue';
import vuetify from 'vite-plugin-vuetify';
import { fileURLToPath, URL } from 'node:url';
import { globSync } from 'node:fs';
import viteCompression from 'vite-plugin-compression';
import { seoInjectPlugin } from './src/lib/plugins/seo-inject.js';
import { prerenderPlugin } from './src/lib/plugins/prerender.js';
import { seoStaticPlugin } from './src/lib/plugins/seo-static.js';
import { augmentSeoConfigWithDocs } from './src/lib/plugins/docs-seo.js';
import { assertConfigLoaded, CONFIG_PLACEHOLDER } from './src/lib/helpers/configGuard.js';

// Load config - will be generated by generateConfig.js script
let appConfig = CONFIG_PLACEHOLDER;
try {
  const configModule = await import('./src/config/index.js');
  appConfig = configModule.default;
} catch {
  console.warn('Could not load config, using defaults. Run npm run config first.');
}

// Project plugins — every `src/modules/<module>/<module>.vite.js` default-exports
// a function `(appConfig, mode) => Plugin | Plugin[]`, appended after the stack
// plugins, so a downstream adds build plugins without editing this stack file.
const projectPluginFactories = await Promise.all(
  globSync('src/modules/*/*.vite.js', { cwd: fileURLToPath(new URL('.', import.meta.url)) })
    .sort()
    .map(async (file) => {
      const factory = (await import(new URL(file, import.meta.url).href)).default;
      if (typeof factory !== 'function') {
        throw new Error(`[vite.config] ${file} must default-export a function (appConfig, mode) => Plugin | Plugin[]`);
      }
      return factory;
    }),
);

// https://vitejs.dev/config/
export default defineConfig(async ({ command, mode }) => {
  assertConfigLoaded(appConfig, mode, { strict: process.env.DEVKIT_VUE_assert_strict === 'true' });
  // Docs-aware SEO layer (off by default). When app.seo.docs.enabled + contentUrl
  // are set, fetch the docs tree at build time and merge the derived prerender /
  // sitemap / llms.txt routes into the config the SEO plugins consume. Fail-soft:
  // any error falls back to the static config — unless app.seo.docs.strict, which
  // fails a production build instead.
  const seoConfig = await augmentSeoConfigWithDocs(appConfig, { production: command === 'build' && mode === 'production' });
  return {
    plugins: [
      seoInjectPlugin(seoConfig),
      prerenderPlugin(seoConfig, mode),
      seoStaticPlugin(seoConfig),
      vue({
        template: {
          compilerOptions: {
            comments: false, // strip HTML comments from templates in every build
            // Support for runtime template compilation
            isCustomElement: (tag) => tag.startsWith('ion-'),
          },
        },
      }),
      // https://github.com/vuetifyjs/vuetify-loader/tree/master/packages/vite-plugin
      vuetify({
        autoImport: true,
      }),
      // Brotli compression for production
      viteCompression({
        verbose: true,
        disable: mode !== 'production',
        threshold: 10240,
        algorithm: 'brotliCompress',
        ext: '.br',
        deleteOriginFile: false,
      }),
      // Gzip compression fallback for production
      viteCompression({
        verbose: true,
        disable: mode !== 'production',
        threshold: 10240,
        algorithm: 'gzip',
        ext: '.gz',
        deleteOriginFile: false,
      }),
      ...projectPluginFactories.flatMap((factory) => factory(seoConfig, mode)),
    ],

    define: {
      __VUE_PROD_HYDRATION_MISMATCH_DETAILS__: 'false',
    },

    resolve: {
      alias: {
        '@': fileURLToPath(new URL('./src', import.meta.url)),
      },
      extensions: ['.js', '.json', '.jsx', '.mjs', '.ts', '.tsx', '.vue'],
    },

    server: {
      port: appConfig.port || 8080,
      strictPort: false,
      // Uncomment to proxy API requests
      // proxy: {
      //   '/api': {
      //     target: 'http://localhost:3000',
      //     changeOrigin: true,
      //   },
      // },
    },

    preview: {
      port: appConfig.port || 8080,
    },

    build: {
      outDir: 'dist',
      assetsDir: 'assets',
      sourcemap: mode !== 'production',
      rollupOptions: {
        output: {
          /**
           * Assign chunk names for selected vendor modules.
           * @param {string} id Bundler module identifier.
           * @returns {string|undefined} Chunk name when matched; otherwise undefined.
           */
          manualChunks(id) {
            if (id.includes('node_modules')) {
              if (['vue', 'vue-router', 'pinia'].some((pkg) => id.includes(`/${pkg}/`))) return 'vue-vendor';
              if (id.includes('/vuetify/')) return 'vuetify-vendor';
              if (['axios', 'lodash-es', 'dayjs'].some((pkg) => id.includes(`/${pkg}/`))) return 'utils-vendor';
            }
          },
        },
      },
      // Increase chunk size warning limit
      chunkSizeWarningLimit: 1000,
    },

    optimizeDeps: {
      include: ['vue', 'vue-router', 'pinia', 'vuetify', 'axios', 'lodash-es', 'dayjs', 'marked', 'aos'],
    },
  };
});
